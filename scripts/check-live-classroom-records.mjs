// Opt-in classroom concurrency check. Creates only synthetic fixtures and removes them in finally.
// RUN_LIVE_CLASSROOM_RECORDS=1 LIVE_APP_ORIGIN=https://ai-town-map.vercel.app node scripts/check-live-classroom-records.mjs
import { createHash, randomBytes, randomUUID } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { loadEnvFile } from "node:process";
import { createInterface } from "node:readline/promises";
import nextEnv from "@next/env";
import pg from "pg";
import { liveTestTarget } from "./live-test-target.mjs";

const actors = [];
const summary = { ok: false, checks: 0, students: 30, saved: 0, replays: 0, failures: [], initialRevision: null, latestRevision: null, recordedRevisions: [], originalSnapshotPreserved: false, cleaned: false };
let admin, connected = false, target, owner;
class CheckFailure extends Error {}
const hash = value => createHash("sha256").update(value).digest();
const token = () => randomBytes(32).toString("base64url");
function check(condition, label) {
  if (!condition) throw new CheckFailure(label);
  summary.checks++;
}
function expect(result, status, label) {
  check(result.status === status, `${label}: expected ${status}; received ${result.status}${/^[A-Z_]+$/.test(result.code ?? "") ? ` ${result.code}` : ""}`);
  return result.data;
}
async function actor(role) {
  const principal = randomUUID(), session = token(), csrf = token();
  const value = { principal, csrf, cookie: `${target.sessionName}=${session}; ${target.csrfName}=${csrf}` };
  actors.push(value);
  await admin.query("INSERT INTO app.principals(id,kind,auth_user_id,account_role) VALUES($1,'account',$2,$3)", [principal, randomUUID(), role]);
  await admin.query("INSERT INTO app_private.sessions(principal_id,token_hash,csrf_hash,expires_at) VALUES($1,$2,$3,now()+interval '1 hour')", [principal, hash(session), hash(csrf)]);
  return value;
}
async function api(path, who, { method = "GET", body, key } = {}) {
  const response = await fetch(new URL(path, target.base), {
    method, redirect: "error", signal: AbortSignal.timeout(90000),
    headers: {
      Cookie: who.cookie, ...(method !== "GET" ? { Origin: target.base, "X-CSRF-Token": who.csrf } : {}),
      ...(body ? { "Content-Type": "application/json" } : {}), ...(key ? { "Idempotency-Key": key } : {}),
    },
    ...(body ? { body: JSON.stringify(body) } : {}),
  });
  let payload;
  try { payload = await response.json(); } catch { payload = null; }
  return { status: response.status, data: payload?.data, code: payload?.error?.code };
}
function aggregateFailures(results, expectedStatus) {
  const counts = new Map();
  for (const result of results) {
    if (result.status === "fulfilled" && result.value.status === expectedStatus) continue;
    const label = result.status === "rejected" ? "REQUEST_FAILED" : `${result.value.status}${/^[A-Z_]+$/.test(result.value.code ?? "") ? ` ${result.value.code}` : ""}`;
    counts.set(label, (counts.get(label) ?? 0) + 1);
  }
  return [...counts].map(([result, count]) => ({ result, count }));
}
async function cleanup() {
  if (!actors.length) { summary.cleaned = true; return; }
  if (!connected) return;
  const principalIds = actors.map(value => value.principal);
  await admin.query("BEGIN");
  try {
    await admin.query("SET CONSTRAINTS ALL DEFERRED");
    // The only owner is generated by this process. The map lock also waits for in-flight saves.
    const mapIds = owner ? (await admin.query("SELECT id FROM app.maps WHERE owner_principal_id=$1 FOR UPDATE", [owner.principal])).rows.map(row => row.id) : [];
    for (const table of ["app.student_analysis_reports", "app.proposal_versions", "app.proposals", "app.audit_events", "app.reports", "app.comments", "app.observation_photos", "app.observations", "app.map_config_revisions", "app.question_versions", "app.questions", "app.rating_options", "app.rating_schemes", "app.emoji_options", "app.categories", "app_private.invites", "app.map_members"]) {
      await admin.query(`DELETE FROM ${table} WHERE map_id=ANY($1::uuid[])`, [mapIds]);
    }
    await admin.query("DELETE FROM app.maps WHERE id=ANY($1::uuid[]) AND owner_principal_id=ANY($2::uuid[])", [mapIds, principalIds]);
    await admin.query("DELETE FROM app_private.idempotency_keys WHERE principal_id=ANY($1::uuid[])", [principalIds]);
    await admin.query("DELETE FROM app_private.sessions WHERE principal_id=ANY($1::uuid[])", [principalIds]);
    await admin.query("DELETE FROM app.principals WHERE id=ANY($1::uuid[])", [principalIds]);
    await admin.query("COMMIT");
    const remaining = await admin.query("SELECT (SELECT count(*) FROM app.principals WHERE id=ANY($1::uuid[]))::int AS principals,(SELECT count(*) FROM app.maps WHERE id=ANY($2::uuid[]))::int AS maps", [principalIds, mapIds]);
    summary.cleaned = remaining.rows[0].principals === 0 && remaining.rows[0].maps === 0;
    if (!summary.cleaned) throw new CheckFailure("synthetic cleanup verification failed");
  } catch (error) { await admin.query("ROLLBACK"); throw error; }
}

try {
  if (process.env.RUN_LIVE_CLASSROOM_RECORDS !== "1") throw new CheckFailure("Set RUN_LIVE_CLASSROOM_RECORDS=1 to opt in");
  nextEnv.loadEnvConfig(process.cwd(), false, { info() {}, error() {} });
  if (existsSync(".env.migrate.local")) loadEnvFile(".env.migrate.local");
  if (!process.env.DATABASE_ADMIN_URL) throw new CheckFailure("DATABASE_ADMIN_URL is required in ignored local environment configuration");
  target = liveTestTarget();
  const catalog = JSON.parse(readFileSync(new URL("../src/lib/emoji-catalog-data.json", import.meta.url), "utf8"));
  const newChoices = ["🦋", "🌷", "🐦", "🌞", "🐞", "🍀"].map(glyph => catalog.entries.find(entry => entry[1] === glyph));
  check(newChoices.every(entry => entry && typeof entry[0] === "string"), "trusted catalog fixture choices must exist");
  admin = new pg.Client({ connectionString: process.env.DATABASE_ADMIN_URL });
  await admin.connect(); connected = true;
  owner = await actor("teacher");
  const students = [];
  for (let index = 0; index < summary.students; index++) students.push(await actor("student"));
  const session = expect(await api("/api/v1/session", owner), 200, "synthetic teacher session");
  check(session?.accountRole === "teacher" && session.canCreateMap === true, "synthetic teacher must be able to create a map");
  const map = expect(await api("/api/v1/maps", owner, { method: "POST", key: randomUUID(), body: {
    themeKey: "custom", themeVersion: 1, title: "학급 동시 관찰 합성 검사 지도", locationLabel: "가상 조사 지역", activityContext: "school",
    visibility: "public", proposalsEnabled: false, moderation: "immediate", custom: {
      pinMode: "single", categories: [{ key: "observation", label: "관찰", color: "#285943", defaultEmojiKey: "tree", emojiOptions: [{ key: "tree", glyph: "🌳", label: "나무" }] }],
    },
  } }), 201, "create synthetic classroom map");
  const base = `/api/v1/maps/${map.id}`;
  for (const [index, student] of students.entries()) await admin.query("INSERT INTO app.map_members(map_id,principal_id,nickname) VALUES($1,$2,$3)", [map.id, student.principal, `가상 학생 ${index + 1}`]);
  // Every device reads the same revision before anybody submits an observation.
  const configurations = await Promise.allSettled(students.map(student => api(`${base}/configuration`, student)));
  check(configurations.every(result => result.status === "fulfilled" && result.value.status === 200), "all synthetic students must load initial configuration");
  const themes = configurations.map(result => result.value.data);
  summary.initialRevision = themes[0].configRevision;
  check(themes.every(config => config.configRevision === summary.initialRevision && config.theme.categories.length === 1 && config.theme.categories[0].emojiOptions.length === 1 && config.theme.questions.length === 0), "all students must retain the same minimal initial configuration");
  const originalSnapshot = JSON.stringify((await admin.query("SELECT definition FROM app.map_config_revisions WHERE map_id=$1 AND revision=$2", [map.id, summary.initialRevision])).rows[0].definition);
  const requests = students.map((student, index) => ({ student, key: randomUUID(), body: {
    configRevision: themes[index].configRevision, title: `합성 관찰 ${index + 1}`, body: "동시 기록 저장을 확인하는 합성 자료이며 실제 학생이나 조사 장소와 관계없습니다.",
    locationLabel: "가상 관찰 장소", locationSource: "manual", location: { lat: 37.5665 + index * 0.00001, lng: 126.978 },
    categoryKey: "observation", emojiKey: index === 0 || index % 3 === 0 ? newChoices[0][0] : index % 3 === 1 ? newChoices[1 + (Math.floor(index / 3) % (newChoices.length - 1))][0] : "tree",
    ratingKey: null, answers: {},
  } }));
  const submit = request => api(`${base}/observations`, request.student, { method: "POST", key: request.key, body: request.body });
  const first = expect(await submit(requests[0]), 201, "first trusted catalog emoji save");
  check(first.emojiKey === newChoices[0][0] && first.status === "published", "first new emoji observation must publish");
  const changed = expect(await api(`${base}/configuration`, owner), 200, "configuration after first emoji save");
  check(changed.configRevision > summary.initialRevision, "first trusted emoji must advance configuration revision");
  // allSettled ensures every concurrent request finishes before an assertion or cleanup runs.
  const concurrent = await Promise.allSettled(requests.slice(1).map(submit));
  summary.saved = 1 + concurrent.filter(result => result.status === "fulfilled" && result.value.status === 201).length;
  summary.failures = aggregateFailures(concurrent, 201);
  check(summary.saved === summary.students, "all students must save with their retained initial revision");
  const saved = [first, ...concurrent.map(result => result.value.data)];
  check(new Set(saved.map(record => record.id)).size === summary.students, "each student save must produce exactly one distinct record");
  const replays = await Promise.allSettled(requests.map(submit));
  summary.replays = replays.filter(result => result.status === "fulfilled" && result.value.status === 200).length;
  summary.failures = aggregateFailures(replays, 200);
  check(summary.replays === summary.students, "exact request-key replays must return 200");
  check(replays.every((result, index) => result.value.data.id === saved[index].id), "every replay must return its original record ID");
  const current = expect(await api(`${base}/configuration`, owner), 200, "latest configuration");
  summary.latestRevision = current.configRevision;
  const expectedNewKeys = new Set(requests.map(request => request.body.emojiKey).filter(key => key !== "tree"));
  check(summary.latestRevision === summary.initialRevision + expectedNewKeys.size, "only distinct newly registered emojis may advance configuration revision");
  const latestOptions = current.theme.categories[0].emojiOptions;
  check(latestOptions.length === expectedNewKeys.size + 1 && new Set(latestOptions.map(emoji => emoji.key)).size === latestOptions.length, "latest configuration must contain each selected emoji exactly once");
  const records = (await admin.query(`SELECT o.id,o.config_revision,c.key AS category_key,e.key AS emoji_key,e.id AS emoji_id,r.definition
    FROM app.observations o JOIN app.categories c ON c.id=o.category_id JOIN app.emoji_options e ON e.id=o.emoji_option_id
    JOIN app.map_config_revisions r ON r.map_id=o.map_id AND r.revision=o.config_revision WHERE o.map_id=$1`, [map.id])).rows;
  check(records.length === summary.students, "database must contain exactly 30 records after replays");
  summary.recordedRevisions = [...new Set(records.map(record => record.config_revision))].sort((a, b) => a - b);
  check(records.every(record => record.config_revision > summary.initialRevision && record.config_revision <= summary.latestRevision && record.definition.categories.find(category => category.key === record.category_key)?.emojiOptions.some(emoji => emoji.key === record.emoji_key) && record.definition.identifiers.emojiOptions[`${record.category_key}:${record.emoji_key}`] === record.emoji_id), "saved records must reference a snapshot containing their exact registered emoji");
  const unchanged = JSON.stringify((await admin.query("SELECT definition FROM app.map_config_revisions WHERE map_id=$1 AND revision=$2", [map.id, summary.initialRevision])).rows[0].definition);
  summary.originalSnapshotPreserved = unchanged === originalSnapshot;
  check(summary.originalSnapshotPreserved, "original configuration snapshot must remain intact");
  const visible = expect(await api(`${base}/observations`, owner), 200, "current classroom observations");
  check(visible.items.length === summary.students && visible.items.every(record => record.status === "published"), "all saved records must appear on the shared map");
  summary.ok = true;
  if (process.env.CLASSROOM_BROWSER_CHECK === "1") {
    // Public synthetic fixture only; Enter or the three-minute deadline always allows cleanup.
    console.log(`${target.base}/?map=${map.id}`);
    const input = createInterface({ input: process.stdin });
    try { await input.question("", { signal: AbortSignal.timeout(180000) }); }
    catch (error) { if (!(error instanceof Error) || error.name !== "AbortError") throw error; }
    finally { input.close(); }
  }
} catch (error) {
  // Never print database errors, session tokens, cookies, usernames, or secrets.
  summary.ok = false;
  summary.error = error instanceof CheckFailure ? error.message : `Check failed (${error instanceof Error ? error.name : "unknown error"})`;
} finally {
  try { await cleanup(); }
  catch (error) { summary.ok = false; summary.cleanupError = error instanceof CheckFailure ? error.message : "Synthetic fixture cleanup failed"; }
  try { if (admin) await admin.end(); }
  catch { summary.ok = false; summary.cleanupError = "Database connection close failed"; }
  console.log(JSON.stringify(summary));
  if (!summary.ok) process.exitCode = 1;
}
